"""Generates the dated posting calendar in 09_SOCIAL_CONTENT_CALENDAR.md (between the CALENDAR markers).
Run from kickstarter/: python tools/make_calendar.py [launch-date YYYY-MM-DD]
Every other date (Next Fest, playtests, pre-launch) is placed relative to the fixed Steam dates (S2) and the launch.
"""
import re
import sys
from datetime import date, timedelta

LAUNCH = date.fromisoformat(sys.argv[1]) if len(sys.argv) > 1 else date(2027, 4, 13)
END = LAUNCH + timedelta(days=30)
START = date(2026, 11, 9)
NEXTFEST = (date(2027, 2, 22), date(2027, 3, 1))  # Steamworks upcoming events, read 2026-10-17
PLAYTESTS = [date(2026, 11, 28), date(2027, 1, 16)]
PRELAUNCH = LAUNCH - timedelta(days=31)

pools = {
    "B": [1, 2, 3, 6, 7, 4, 10, 12, 8, 15, 9, 13, 21, 5, 16, 14, 11, 18, 19, 20, 22, 17, 31, 32],
    "C": [24, 8, 2, 16, 5, 3],
    "D": [23, 14, 21],
    "E": [26, 27, 7, 23, 17, 24, 15, 22],
    "F": [27, 28, 29, 13, 32, 9, 22, 20, 12],
}
FOOTAGE_NEEDED = {1, 2, 4, 6, 9, 10, 14, 15, 16, 22, 29, 31, 32}


def phase(d):
    if d < date(2027, 2, 1):
        return "B"
    if d <= NEXTFEST[1]:
        return "C"
    if d < PRELAUNCH:
        return "D"
    if d < LAUNCH:
        return "E"
    if d <= END:
        return "F"
    return None


rows = []
used = {k: 0 for k in pools}
d = START
while d <= END:
    if d.weekday() in (0, 2, 4):  # Mon, Wed, Fri
        ph = phase(d)
        note = ""
        if any(timedelta(0) < (p - d) <= timedelta(days=4) for p in PLAYTESTS):
            c, note = 25, f"playtest {min(p for p in PLAYTESTS if p > d):%b %d}"
        elif NEXTFEST[0] <= d <= NEXTFEST[1]:
            c, note = 24, "Next Fest demo is live" if d.weekday() == 0 else "Next Fest"
            c = pools["C"][used["C"] % len(pools["C"])]
            used["C"] += 1
        elif END - timedelta(days=3) <= d <= END:
            c, note = 30, "final 72 h"
        elif d.weekday() == 4 and ph in ("B", "C", "D"):
            c, note = None, "re-cut the best performer of the last 2 weeks with a new hook"
        else:
            pool = pools[ph]
            if used[ph] < len(pool):
                c = pool[used[ph]]
                used[ph] += 1
            else:
                c, note = None, "re-cut the best performer"
        cta = {"B": "Wishlist / Playtest", "C": "Play the demo · Wishlist", "D": "Wishlist", "E": "Notify me on Kickstarter",
               "F": "Back it"}[ph]
        rows.append((d, ph, c, cta, note))
    d += timedelta(days=1)

events = [(START - timedelta(days=1), "—", "Steam Coming Soon page live (phase A target)"),
          *[(p, "B", "Playtest weekend (Discord matchmaking, survey after round 3)") for p in PLAYTESTS],
          (NEXTFEST[0], "C", "Steam Next Fest starts (Feb 22 – Mar 1)"),
          (PRELAUNCH, "E", "Kickstarter pre-launch page live (after review)"),
          (LAUNCH, "F", "LAUNCH 15:00 CET: email E2, Discord, socials, livestream"),
          (LAUNCH + timedelta(days=1), "F", "Update #1: thank you + day-1 numbers"),
          (END - timedelta(days=2), "F", "Final 48 h update + email E5"),
          (END, "F", "Campaign ends 15:00 CET; final livestream")]

out = ["<!-- CALENDAR:START (generated by tools/make_calendar.py; edit the script, not this table) -->", "",
       f"Launch {LAUNCH:%a %d %b %Y}, end {END:%a %d %b %Y} (30 days).", "",
       "**Key dates**", "", "| Date | Phase | Event |", "|---|---|---|"]
out += [f"| {e[0]:%a %d %b %Y} | {e[1]} | {e[2]} |" for e in sorted(events)]
out += ["", "**Posts** (Mon/Wed/Fri)", "", "| Date | Phase | Concept | CTA | Note |", "|---|---|---|---|---|"]
for d, ph, c, cta, note in rows:
    cs = f"#{c}" + (" ⚠" if c in FOOTAGE_NEEDED else "") if c else "re-cut"
    out.append(f"| {d:%a %d %b %Y} | {ph} | {cs} | {cta} | {note} |")
out += ["", f"{len(rows)} posts. ⚠ = needs the 4-player capture session (07 §4) before that date.", "",
        "<!-- CALENDAR:END -->"]

p = "09_SOCIAL_CONTENT_CALENDAR.md"
s = open(p, encoding="utf-8").read()
block = "\n".join(out)
if "<!-- CALENDAR:START" in s:
    s = re.sub(r"<!-- CALENDAR:START.*?<!-- CALENDAR:END -->", lambda m: block, s, flags=re.S)
else:
    s = s.rstrip() + "\n\n" + block + "\n"
open(p, "w", encoding="utf-8").write(s)
print(f"{len(rows)} posts written; launch {LAUNCH}, pre-launch {PRELAUNCH}")
